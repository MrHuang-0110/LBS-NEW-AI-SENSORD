uint8_t KEY_status = 0;            //按键状态，1按下，0松开
static void GetKeyStatus(uint16_t GPIO_Pin)
{
    uint16_t m =6000;	

	if(GPIO_Pin == KEY_Pin)		                                //KEY=PA12
	{	  
		while(m--);
        
		if( HAL_GPIO_ReadPin(KEY_GPIO_Port,KEY_Pin) ==0 )		
		{
		 KEY_status = 1;					
		}
		else KEY_status = 0;
	}   
}
void HAL_GPIO_EXTI_Rising_Callback(uint16_t GPIO_Pin)
{
	GetKeyStatus(GPIO_Pin);    
}

void HAL_GPIO_EXTI_Falling_Callback(uint16_t GPIO_Pin)
{
	GetKeyStatus(GPIO_Pin);
}
